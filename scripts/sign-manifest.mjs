// Sign the shipped data files (BLAKE3 + Ed25519). The private key lives OUTSIDE the repo.
//
//   node scripts/sign-manifest.mjs --keygen     new key pair: private key -> ~/.config/happyfeet/
//                                               (mode 0600), public key -> web/integrity-pubkey.js
//   node scripts/sign-manifest.mjs              write web/public/data/params.json, hash every
//                                               data file, write + sign web/public/integrity/manifest.json
//   node scripts/sign-manifest.mjs --verify     verify on disk; also list data files NOT covered
//
// Env: HAPPYFEET_SIGNING_KEY=/path/to/key.pem overrides the private key location.
import { createPrivateKey, createPublicKey, generateKeyPairSync, sign } from "node:crypto";
import { mkdir, readFile, readdir, writeFile, chmod } from "node:fs/promises";
import { existsSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { canonicalManifest, keyId, blake3Hex, verifyAll, PATH_ALLOW, b64 } from "../web/integrity.js";
import { SURVIVAL_PARAMS, DEFAULT_CREW, SCENARIOS } from "../web/survival.js";

const WEB = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "web");
const KEY = process.env.HAPPYFEET_SIGNING_KEY || path.join(os.homedir(), ".config", "happyfeet", "manifest-ed25519.pem");
const OUT_DIR = path.join(WEB, "public", "integrity");
const PUB_JS = path.join(WEB, "integrity-pubkey.js");
const rawPub = (pubKeyObj) => Buffer.from(pubKeyObj.export({ format: "jwk" }).x, "base64url");

async function listData(dir = path.join(WEB, "public", "data"), rel = "public/data") {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = `${rel}/${e.name}`;
    if (e.isDirectory()) out.push(...await listData(path.join(dir, e.name), p));
    else if (PATH_ALLOW.test(p)) out.push(p);
  }
  return out.sort();
}

if (process.argv.includes("--keygen")) {
  if (existsSync(KEY) && !process.argv.includes("--force")) { console.error(`${KEY} exists; pass --force to replace it`); process.exit(1); }
  const { privateKey, publicKey } = generateKeyPairSync("ed25519");
  await mkdir(path.dirname(KEY), { recursive: true, mode: 0o700 });
  await writeFile(KEY, privateKey.export({ format: "pem", type: "pkcs8" }), { mode: 0o600 });
  await chmod(KEY, 0o600);
  const pub = rawPub(publicKey);
  await writeFile(PUB_JS, `// Pinned Ed25519 public key for web/public/integrity/manifest.json (generated by scripts/sign-manifest.mjs --keygen).\n` +
    `// The private key is kept offline by the signer and is never committed.\n` +
    `export const MANIFEST_PUBLIC_KEY = "${pub.toString("base64")}";\nexport const MANIFEST_KEY_ID = "${keyId(pub)}";\n`);
  console.log(`private key: ${KEY} (0600, keep it out of git)\npublic key id: ${keyId(pub)} -> ${path.relative(process.cwd(), PUB_JS)}`);
  process.exit(0);
}

if (process.argv.includes("--verify")) {
  const { MANIFEST_PUBLIC_KEY } = await import(PUB_JS);
  const manifestText = await readFile(path.join(OUT_DIR, "manifest.json"), "utf8");
  const signatureB64 = await readFile(path.join(OUT_DIR, "manifest.sig"), "utf8");
  const r = await verifyAll({ manifestText, signatureB64, publicKeyB64: MANIFEST_PUBLIC_KEY, readFile: (p) => readFile(path.join(WEB, p)) });
  for (const f of r.files) console.log(`${f.status.padEnd(9)} ${f.path}`);
  const listed = new Set((r.manifest?.files ?? []).map((f) => f.path));
  const extra = (await listData()).filter((p) => !listed.has(p));
  for (const p of extra) console.log(`UNSIGNED  ${p}`);
  console.log(r.ok && !extra.length ? "OK: signature valid, every data file matches" : `FAIL: ${r.error?.message ?? `${extra.length} unsigned file(s)`}`);
  process.exit(r.ok && !extra.length ? 0 : 1);
}

// sign
if (!existsSync(KEY)) { console.error(`No private key at ${KEY}. Run --keygen first (or set HAPPYFEET_SIGNING_KEY).`); process.exit(1); }
const priv = createPrivateKey(await readFile(KEY));
const pub = rawPub(createPublicKey(priv));
const { MANIFEST_PUBLIC_KEY } = await import(PUB_JS);
if (MANIFEST_PUBLIC_KEY !== pub.toString("base64")) { console.error("Private key does not match web/integrity-pubkey.js"); process.exit(1); }

// params.json: the survival coefficients the page uses, as a signed file (assertion P3: generated, never hand-edited)
const params = { schema: "happyfeet.params/1", source: "web/survival.js (SURVIVAL_PARAMS, DEFAULT_CREW, SCENARIOS); documented in docs/assumptions.md",
  params: SURVIVAL_PARAMS, crew: DEFAULT_CREW, scenarios: Object.fromEntries(Object.entries(SCENARIOS).map(([k, v]) => [k, v.label])) };
await writeFile(path.join(WEB, "public", "data", "params.json"), JSON.stringify(params, null, 1) + "\n");

const files = [];
for (const p of await listData()) {
  const bytes = await readFile(path.join(WEB, p));
  files.push({ path: p, size: bytes.length, blake3: blake3Hex(bytes) });
}
const text = canonicalManifest({ created: new Date().toISOString(), key_id: keyId(pub), files });
await mkdir(OUT_DIR, { recursive: true });
await writeFile(path.join(OUT_DIR, "manifest.json"), text);
await writeFile(path.join(OUT_DIR, "manifest.sig"), b64(sign(null, Buffer.from(text, "utf8"), priv)) + "\n");
console.log(`signed ${files.length} files with key ${keyId(pub)}:`);
for (const f of files) console.log(`  ${f.blake3.slice(0, 12)}  ${String(f.size).padStart(9)}  ${f.path}`);
